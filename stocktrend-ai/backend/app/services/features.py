import pandas as pd
import numpy as np

def _rsi(series: pd.Series, period: int = 14) -> pd.Series:
    delta = series.diff()
    up = delta.clip(lower=0)
    down = -delta.clip(upper=0)
    ma_up = up.ewm(com=period - 1, adjust=False).mean()
    ma_down = down.ewm(com=period - 1, adjust=False).mean()
    rs = ma_up / ma_down
    return 100 - (100 / (1 + rs))

def _macd(series: pd.Series, fast: int = 12, slow: int = 26, signal: int = 9):
    ema_fast = series.ewm(span=fast, adjust=False).mean()
    ema_slow = series.ewm(span=slow, adjust=False).mean()
    macd_line = ema_fast - ema_slow
    signal_line = macd_line.ewm(span=signal, adjust=False).mean()
    histogram = macd_line - signal_line
    return macd_line, signal_line, histogram

def _sma(series: pd.Series, window: int):
    return series.rolling(window=window).mean()

def _ema(series: pd.Series, window: int):
    return series.ewm(span=window, adjust=False).mean()

def _bb_percent_b(series: pd.Series, window: int = 20, num_std: int = 2):
    sma = series.rolling(window).mean()
    std = series.rolling(window).std()
    upper = sma + num_std * std
    lower = sma - num_std * std
    return (series - lower) / (upper - lower)

def _stoch_k(high: pd.Series, low: pd.Series, close: pd.Series, window: int = 14):
    lowest_low = low.rolling(window).min()
    highest_high = high.rolling(window).max()
    return 100 * (close - lowest_low) / (highest_high - lowest_low)

def _atr(high: pd.Series, low: pd.Series, close: pd.Series, period: int = 14):
    tr1 = high - low
    tr2 = (high - close.shift()).abs()
    tr3 = (low - close.shift()).abs()
    tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
    return tr.ewm(alpha=1/period, adjust=False).mean()

def add_technical_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add all required technical indicators to a OHLCV DataFrame.
    Expected columns: ['Open','High','Low','Close','Volume'] with DateTime index.
    Returns a new DataFrame with original columns plus feature columns.
    """
    df = df.copy()
    close = df['Close']
    high = df['High']
    low = df['Low']
    volume = df['Volume']

    df['RSI_14'] = _rsi(close, 14)
    macd_line, signal_line, hist = _macd(close)
    df['MACD'] = macd_line
    df['MACD_signal'] = signal_line
    df['MACD_hist'] = hist
    df['SMA20'] = _sma(close, 20)
    df['EMA50'] = _ema(close, 50)
    df['BB_%B'] = _bb_percent_b(close, 20, 2)
    df['Stoch_%K'] = _stoch_k(high, low, close, 14)
    df['ATR_14'] = _atr(high, low, close, 14)
    # Returns
    df['Return_1d'] = close.pct_change(1)
    df['Return_5d'] = close.pct_change(5)
    # Volume change (percentage)
    df['Vol_Change_1d'] = volume.pct_change(1)
    # 10‑day volatility (std of returns)
    df['Volatility_10d'] = df['Return_1d'].rolling(10).std()
    # Drop rows with NaNs generated by rolling windows
    df = df.dropna()
    return df
